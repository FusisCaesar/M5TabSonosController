"""Build GFX fonts with Latin accents for the Tab5 UI.

Segoe UI covers the letters Sonos puts in titles (Í, é, ñ, ü, and Latin Extended-A).
The Adafruit FreeSans fonts built into M5GFX stop at ASCII, which draws a box.
"""
import os
from PIL import Image, ImageDraw, ImageFont

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "font_ui.h")
FIRST = 0x20
LAST = 0x17F


def pack(font, cp):
    if cp < 0x20 or 0x7F <= cp <= 0x9F or cp == 0xAD:
        adv = max(4, int(round(font.getlength(" "))))
        return None, adv
    ch = chr(cp)
    bbox = font.getbbox(ch, anchor="ls")
    left, top, right, bottom = bbox
    width = max(0, right - left)
    height = max(0, bottom - top)
    advance = max(width, int(round(font.getlength(ch))))
    if advance <= 0:
        advance = max(4, int(round(font.getlength(" "))))
    if width == 0 or height == 0:
        return None, advance
    img = Image.new("1", (width, height), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=1, anchor="ls")
    # M5GFX reads a glyph as one bitstream, width bits per row, with no padding.
    bits = width * height
    data = bytearray((bits + 7) // 8)
    i = 0
    for y in range(height):
        for x in range(width):
            if img.getpixel((x, y)):
                data[i // 8] |= 0x80 >> (i % 8)
            i += 1
    if left < -127 or left > 127 or top < -127 or top > 127:
        raise SystemExit(f"offset out of int8 for U+{cp:04X}")
    if advance > 255 or height > 255 or width > 255:
        raise SystemExit(f"glyph U+{cp:04X} does not fit a GFX font ({width}x{height} adv {advance})")
    return (bytes(data), width, height, advance, left, top), advance


def preview(path, size, chars):
    font = ImageFont.truetype(path, size)
    for ch in chars:
        packed, _ = pack(font, ord(ch))
        if not packed:
            print(ch, "empty")
            continue
        data, width, height, _advance, _left, _top = packed
        print(f"  {ch} {width}x{height}")
        i = 0
        for _y in range(height):
            row = []
            for _x in range(width):
                on = data[i // 8] & (0x80 >> (i % 8))
                row.append("#" if on else ".")
                i += 1
            print("   " + "".join(row))


def emit(name, path, size, lines):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    y_advance = min(255, ascent + descent)
    bitmaps = bytearray()
    glyphs = []
    for cp in range(FIRST, LAST + 1):
        packed, _adv = pack(font, cp)
        if packed is None:
            adv = _adv
            glyphs.append((0, 0, 0, adv, 0, 0))
            continue
        data, width, height, advance, left, top = packed
        glyphs.append((len(bitmaps), width, height, advance, left, top))
        bitmaps.extend(data)
    if len(bitmaps) > 512 * 1024:
        raise SystemExit(f"{name} bitmap is {len(bitmaps)} bytes")
    lines.append(f"static const uint8_t {name}Bitmaps[] PROGMEM = {{")
    for i in range(0, len(bitmaps), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in bitmaps[i : i + 16])
        lines.append(f"  {chunk},")
    lines.append("};")
    lines.append(f"static const GFXglyph {name}Glyphs[] PROGMEM = {{")
    for cp, (off, w, h, adv, xo, yo) in enumerate(glyphs, start=FIRST):
        lines.append(f"  {{ {off:5d}, {w:3d}, {h:3d}, {adv:3d}, {xo:4d}, {yo:4d} }}, // U+{cp:04X}")
    lines.append("};")
    lines.append(f"static const GFXfont {name} PROGMEM = {{")
    lines.append(f"  (uint8_t*){name}Bitmaps, (GFXglyph*){name}Glyphs, 0x{FIRST:02X}, 0x{LAST:02X}, {y_advance} }};")
    lines.append("")
    ink = font.getbbox("ÍAg", anchor="ls")
    print(f"{name}: {len(bitmaps)} bitmap bytes, {len(glyphs)} glyphs, yAdvance {y_advance}, ÍAg {ink}")


def main():
    lines = [
        "#pragma once",
        "// Generated by tools/make_font.py. Latin-1 and Latin Extended-A, so titles keep accents.",
        "",
    ]
    win = "C:/Windows/Fonts/"
    emit("fontTitle", win + "segoeuib.ttf", 48, lines)
    emit("fontUi", win + "segoeuib.ttf", 30, lines)
    emit("fontBody", win + "segoeui.ttf", 30, lines)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
